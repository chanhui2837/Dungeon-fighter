let currentLanguage = 'en';

LANG.init = function() {
    const saved = localStorage.getItem('game_language');
    if (saved && SUPPORTED_LANGS.includes(saved)) {
        currentLanguage = saved;
    } else if (api.userData && api.userData.language) {
        currentLanguage = api.userData.language;
    } else {
        const browserLang = (navigator.language || 'en').split('-')[0];
        currentLanguage = SUPPORTED_LANGS.includes(browserLang) ? browserLang : 'en';
    }
    document.documentElement.lang = currentLanguage;
    return currentLanguage;
};

LANG.t = function(key) {
    const dict = TRANSLATIONS[currentLanguage] || TRANSLATIONS['en'];
    return dict[key] || TRANSLATIONS['en'][key] || key;
};

LANG.setLanguage = function(lang) {
    if (!SUPPORTED_LANGS.includes(lang)) return;
    currentLanguage = lang;
    localStorage.setItem('game_language', lang);
    document.documentElement.lang = lang;
    if (api.userData) {
        api.updateUser({ language: lang });
    }
};

